// Werte eines Turms auf Stufe lvl (0..5)
export function towerStats(def, lvl, buff = 0) {
  const s = {
    dmg: def.dmg * Math.pow(1.38, lvl) * (1 + buff),
    range: def.range * (1 + 0.07 * lvl),
    rate: def.rate * Math.pow(1.1, lvl),
    speed: (def.speed || 0) * (1 + 0.06 * lvl),
    splash: def.splash ? def.splash * (1 + 0.08 * lvl) : 0,
    chain: def.chain ? def.chain + (lvl >= 3 ? 1 : 0) + (lvl >= 5 ? 1 : 0) : 0,
    targets: def.targets ? def.targets + (lvl >= 5 ? 1 : 0) : 1,
    pierce: def.pierce ? def.pierce + lvl : 0,
    drones: def.drones ? def.drones + (lvl >= 3 ? 1 : 0) + (lvl >= 5 ? 1 : 0) : 0,
    income: def.income ? Math.round(def.income * (1 + 0.7 * lvl)) : 0,
    healEvery: def.healEvery ? def.healEvery * Math.pow(0.85, lvl) : 0,
    buffAmt: def.buff ? def.buff + 0.05 * lvl : 0,
    auraSlow: def.auraSlow ? Math.min(0.6, def.auraSlow + 0.04 * lvl) : 0,
    slow: def.slow ? [Math.min(0.75, def.slow[0] + 0.04 * lvl), def.slow[1]] : null,
    burn: def.burn ? [def.burn[0] * Math.pow(1.35, lvl) * (1 + buff), def.burn[1]] : null,
    poison: def.poison ? [def.poison[0] * Math.pow(1.35, lvl) * (1 + buff), def.poison[1]] : null,
    stun: def.stun ? def.stun * (1 + 0.1 * lvl) : 0,
    knock: def.knock ? def.knock * (1 + 0.08 * lvl) : 0,
    curse: def.curse ? [def.curse[0] + 0.05 * lvl, def.curse[1]] : null,
    maxMines: def.maxMines ? def.maxMines + lvl : 0,
  };
  if (buff) s.range *= 1.08;
  return s;
}

export function upgradeCost(def, lvl) {
  // Kosten für Upgrade von lvl -> lvl+1
  return Math.round(def.cost * (0.55 + 0.35 * lvl) / 5) * 5;
}

